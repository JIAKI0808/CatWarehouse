"""语言包目录（数据层）—— 后端自己产生的用户可见文案的本地化。

## 这个包**负责**什么

只负责**后端自己产生的文案**：`HTTPException` 的 `detail`、CRUD 的 404 文案
（`Category not found` 这一类）。这些字符串**在接口响应里一个字都没改**
（本次的硬约束），语言包做的是给三端一张「原文 → 本地化文本」的对照表，
前端拿到 `detail` 后可以查表显示成用户语言。

## 这个包**不**负责什么（刻意的边界）

**不**管界面文案。设置页的标题、按钮、表单标签由**各前端自己的语言包**负责
（`Cw_WebUi/src/locales/`、`CwMobile/src/locales/`）。
理由：界面文案必须在**后端还没应答时**就能渲染（离线 / 连不上服务端是既有的正常状态），
把它做成需要先请求一次的远程依赖，等于给首屏加一个失败点。
后端只做「它真正拥有、且只有它知道」的那部分。

## 结构

| 文件 | 职责 |
| --- | --- |
| `catalog.py` | 扫描语言包、归一化语言标签、加载内容（带缓存） |
| `<locale>.json` | 语言包本体，文件名即 locale（如 `zh-CN.json`） |

新增一门语言 = **只丢一个 `<locale>.json` 进来**，`catalog.py` 按文件名自动发现，
不需要改任何代码。语言清单由 `GET /api/i18n/locales` 下发。

本文件刻意**不** import 子模块（与 `core/`、`voice/`、`receipts/`、`api/` 同策略）。
"""
