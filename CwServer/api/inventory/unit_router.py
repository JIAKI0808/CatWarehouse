"""计量单位字典 —— 「通用化」环新增。

## 为什么需要它

`SubCategory.unit` 一直是**自由文本**，而新建子分类的表单里把默认值写死成 `'个'`
（两端共 7 处）。两件事都不好：

1. **自由文本没有约束** —— 「斤」「市斤」「500g」会同时出现在同一列，
   数据统计与票据对照都会失准；
2. **写死的默认值是语言相关的** —— `plan.md` §C12 记过：把它跟着界面语言翻译，
   会让同一张表里中英混杂。真正的解法不是翻译它，而是**让它可被选择**。

## 这个端点做什么、不做什么

- **做**：给出一份常用单位清单，供表单做「选或自由输入」；
- **不做**：不把 `unit` 改成枚举代码。那需要一次**数据迁移**（现有行的 `'个'`
  要变成 `'piece'` 之类），而 `unit` 还会被 OCR / 语音两条写入路径碰到 ——
  那是另一个项目级的决定，不该夹在本环里。**保留自由文本**，
  字典只是**建议**，不是约束。

## 放哪个分区

放在 `inventory` 而不是 `system`：单位是**库存词汇**（`SubCategory.unit` 属于库存），
而 `currencies` 放 `system` 是因为它服务的是全站计价。分区按功能而不是按「像参考数据」来分。
"""

import logging

from fastapi import APIRouter

logger = logging.getLogger(__name__)
router = APIRouter()

#: 常用单位。**中英混排是刻意的** —— 它们是要写进数据库的**数据**，
#: 不是界面文案，所以不该跟着界面语言变（见 §C12 的同一判断）。
#: 顺序有意义：`'个'` 排第一，表单默认值取它，从而不再写死。
UNITS = [
    "个",
    "包",
    "箱",
    "袋",
    "瓶",
    "盒",
    "桶",
    "卷",
    "件",
    "提",
    "条",
    "张",
    "支",
    "斤",
    "克",
    "公斤",
    "升",
    "毫升",
    "kg",
    "g",
    "L",
    "ml",
]


@router.get("/units")
async def list_units():
    """常用单位清单。前端用它做「选或自由输入」，**不强制**取值。"""
    return UNITS
